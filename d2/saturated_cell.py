def _report(tag, res, expect=None):
    ok = "" if expect is None else ("  [expected %s -> %s]" % (
        expect, "OK" if res["verdict"] == expect else "*** MISMATCH ***"))
    print("  %-52s %-10s dim=%-4s %7.2fs  vars=%-3s gens=%s%s"
          % (tag, res["verdict"], res.get("dim"), res["wall"],
             res.get("n_ring_vars"), res.get("n_gens"), ok), flush=True)
    return res


