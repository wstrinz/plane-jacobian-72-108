class CellSystem:
    """Polynomials + endpoint ideals + essential nonvanishing for one run."""

    def __init__(self, label, polys, endpoint_ideals, essential, marked, note=""):
        self.label = label
        self.polys = polys                  # d2, d1, sigma, e (sympy)
        self.endpoint_ideals = endpoint_ideals   # [(name, [gens])] -> sat by IDEAL
        self.essential = essential          # [(name, poly)]        -> sat by ELEMENT
        self.marked = marked
        self.note = note


def build_cell_system(case, *, d2_deg_max, d2_deg_min, g_deg_max, g_deg_min,
                      sat_Gr=True, label="cell", sigma_generic=False):
    """The saturated flag-case ansatz.

    `d2_deg_min=None` means the union INCLUDES `d2 == 0` (no endpoint ideal);
    otherwise the endpoint ideal `<a_{dmin},...,a_{dmax}>` encodes exactly
    `deg d2 in [dmin, dmax]`.  Same for `G` (the sigma cofactor).

    NOTHING is divided by a leading coefficient anywhere in here.
    """
    a_t = case["a_t"]
    b = tuple(case["b"])
    sumb = sum(b)
    marked = sumb > 0
    if sum(1 for x in b if x > 0) > 1:
        raise SystemExit("FAIL: cell has >1 marked root; this pilot handles 0 or 1")

    root_factor = (Y - R) ** sumb if marked else sp.Integer(1)
    e = sp.expand(GAMMA * (Y + 1) ** a_t * root_factor)
    if sp.Poly(e, Y).degree() != _d(case["states"][0]["deg_e"]):
        raise SystemExit("FAIL: forced e has degree %d but the cell records deg_e=%s"
                         % (sp.Poly(e, Y).degree(), case["states"][0]["deg_e"]))

    acoef = tuple(sp.symbols("a0:%d" % (d2_deg_max + 1)))
    d2 = sum(c * Y ** i for i, c in enumerate(acoef))
    d1 = sp.Integer(0) if case["branch"] == "T2" else None
    if d1 is None:
        raise SystemExit("FAIL: this pilot only builds T2 cells (d1 == 0)")

    endpoint = []
    if d2_deg_min is not None:
        endpoint.append(("d2:deg in [%d,%d]" % (d2_deg_min, d2_deg_max),
                         list(acoef[d2_deg_min:d2_deg_max + 1])))
    essential = [("gamma != 0", GAMMA)]

    if sigma_generic:
        # NO pattern-B divisor structure on sigma at all: the honest cell,
        # relaxed further than the lane that produced the known kills.
        smax = g_deg_max + 2 * sumb
        smin = None if g_deg_min is None else g_deg_min + 2 * sumb
        scoef = tuple(sp.symbols("s0:%d" % (smax + 1)))
        sigma = sum(c * Y ** i for i, c in enumerate(scoef))
        if smin is not None:
            endpoint.append(("sigma:deg in [%d,%d]" % (smin, smax),
                             list(scoef[smin:smax + 1])))
        note = ("e = gamma (y+1)^%d (y-r)^%d ; sigma GENERIC deg <= %d ; "
                "d2 generic deg <= %d ; d1 = 0" % (a_t, sumb, smax, d2_deg_max))
    else:
        gcoef = tuple(sp.symbols("g0:%d" % (g_deg_max + 1)))
        G = sum(c * Y ** i for i, c in enumerate(gcoef))
        sigma = sp.expand(((Y - R) ** (2 * sumb) if marked else sp.Integer(1)) * G)
        if g_deg_min is not None:
            endpoint.append(("G:deg in [%d,%d]" % (g_deg_min, g_deg_max),
                             list(gcoef[g_deg_min:g_deg_max + 1])))
        if sat_Gr and marked:
            essential.append(("G(r) != 0  [v_r(sigma) = %d exactly]" % (2 * sumb),
                              qreduce(G.subs(Y, R), marked)))
        note = ("e = gamma (y+1)^%d (y-r)^%d ; sigma = (y-r)^%d G, deg G <= %d ; "
                "d2 generic deg <= %d ; d1 = 0"
                % (a_t, sumb, 2 * sumb, g_deg_max, d2_deg_max))
    return CellSystem(label, dict(d2=d2, d1=d1, sigma=sigma, e=e),
                      endpoint, essential, marked, note)


def strata_covered(case, cs, d2_deg_max, d2_deg_min, g_deg_max, g_deg_min):
    """Which of the cell's states this saturated locus is the union of."""
    sumb = sum(case["b"])
    out = []
    for st in case["states"]:
        dd2, dsig = _d(st["deg_d2"]), _d(st["deg_sigma"])
        degG = None if dsig is None else dsig - 2 * sumb
        lo2 = 0 if d2_deg_min is None else d2_deg_min
        loG = 0 if g_deg_min is None else g_deg_min
        if dd2 is not None and lo2 <= dd2 <= d2_deg_max and \
           degG is not None and loG <= degG <= g_deg_max:
            out.append({"deg_d2": dd2, "deg_sigma": dsig, "deg_G": degG})
    return out


