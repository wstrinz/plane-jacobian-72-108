def qpoly(var):
    return sum(c * var ** (4 - i) for i, c in enumerate(Q_COEFFS))


QR_POLY = sp.Poly(qpoly(R), R)


def qreduce(expr, marked=True):
    """Reduce an expression modulo q(r) (the marked-root relation)."""
    expr = sp.expand(sp.sympify(expr))
    if not marked or expr == 0 or not expr.has(R):
        return expr
    num, den = sp.fraction(sp.together(expr))
    if den.has(R):
        raise ValueError("r in denominator")
    rem = sp.rem(sp.Poly(sp.expand(num), R), QR_POLY).as_expr()
    return sp.cancel(rem / den)


