def poly_to_singular_exact(expr, gens):
    """INTEGER-coefficient Singular text (Singular parses `gm^8/N` as
    `gm^(8/N)`, so rationals must be cleared, never emitted)."""
    expr = sp.cancel(sp.sympify(expr))
    if expr == 0:
        return "0"
    num, den = sp.fraction(sp.together(expr))
    dpoly = sp.Poly(sp.expand(den), *gens)
    if dpoly.total_degree() != 0:
        raise ValueError("non-constant denominator: %s" % den)
    poly = sp.Poly(sp.expand(num), *gens)
    L = sp.Integer(1)
    for c in poly.coeffs():
        L = sp.ilcm(L, sp.denom(c))
    terms = []
    for monom, coeff in poly.terms():
        scaled = sp.nsimplify(coeff * L)
        if not scaled.is_Integer:                 # never truncate (SERIALIZER trap)
            raise ValueError("non-integer coefficient %s after clearing" % scaled)
        c = int(scaled)
        if c == 0:
            continue
        factors = [str(c)] if (c != 1 or all(e == 0 for e in monom)) else []
        for g, e in zip(gens, monom):
            if e == 1:
                factors.append(g.name)
            elif e > 1:
                factors.append("%s^%d" % (g.name, e))
        terms.append("*".join(factors) if factors else str(c))
    return ("+".join(terms)).replace("+-", "-") or "0"


def saturated_program(gens, ring_vars, endpoint_ideals, essential, char=0):
    """`ideal I` -> iterated `sat(.,B)[1]` -> `std` -> unit test + dim."""
    def emit(expr):
        if char == 0:
            return poly_to_singular_exact(expr, ring_vars)
        return mt.poly_to_singular_modp(expr, ring_vars, char)

    lines = ['LIB "elim.lib";',
             "ring Rg = %d,(%s),dp;" % (char, ",".join(v.name for v in ring_vars))]
    names = []
    for i, g in enumerate(gens):
        s = emit(g)
        if s == "0":
            continue
        lines.append("poly f%d = %s;" % (i, s))
        names.append("f%d" % i)
    lines.append("ideal I = %s;" % (",".join(names) if names else "0"))
    lines.append("ideal Is = I;")
    for j, (_name, bgens) in enumerate(endpoint_ideals):
        txt = ",".join(emit(b) for b in bgens)
        lines.append("ideal B%d = %s;" % (j, txt))
        lines.append("Is = sat(Is,B%d)[1];" % j)
    for j, (_name, f) in enumerate(essential):
        lines.append("poly s%d = %s;" % (j, emit(f)))
        lines.append("Is = sat(Is,s%d)[1];" % j)
    lines.append("ideal G = std(Is);")
    lines.append("int u = (reduce(1,G)==0);")
    lines.append('"@@UNIT";')
    lines.append("u;")
    lines.append('"@@DIM";')
    lines.append("dim(G);")
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def run_singular(program, timeout):
    t0 = time.monotonic()
    try:
        cp = subprocess.run(WSL, input=program, text=True, encoding="utf-8",
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return {"status": "timeout", "verdict": "TIMEOUT", "unit": None,
                "dim": None, "wall": round(time.monotonic() - t0, 2)}
    out = (cp.stdout or "").replace("\x00", "")
    err = (cp.stderr or "").replace("\x00", "")
    import re
    um = re.search(r"@@UNIT\s*\r?\n\s*(-?\d+)", out + "\n" + err)
    dm = re.search(r"@@DIM\s*\r?\n\s*(-?\d+)", out + "\n" + err)
    unit = None if um is None else bool(int(um.group(1)))
    return {"status": "ok" if cp.returncode == 0 else "proc_error",
            "verdict": "UNIT" if unit else ("PROPER" if unit is False else "PARSE_FAIL"),
            "unit": unit, "dim": None if dm is None else int(dm.group(1)),
            "wall": round(time.monotonic() - t0, 2),
            "stderr": err.strip()[:400], "stdout_tail": out.strip()[-400:]}


def solve(cs, gens, *, char=0, timeout=600.0, extra_gens=()):
    members = list(gens) + list(extra_gens)
    if cs.marked:
        members = members + [qpoly(R)]
    ring_vars = mt.ring_vars_of(members,
                                extra=[b for _n, bg in cs.endpoint_ideals for b in bg]
                                + [GAMMA])
    prog = saturated_program(members, ring_vars, cs.endpoint_ideals,
                             cs.essential, char=char)
    res = run_singular(prog, timeout)
    res["n_gens"] = len(members)
    res["n_ring_vars"] = len(ring_vars)
    res["ring_vars"] = [v.name for v in ring_vars]
    res["program_bytes"] = len(prog)
    res["char"] = char
    return res, prog


