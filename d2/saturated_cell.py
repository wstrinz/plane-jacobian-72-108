def f31_generators(cs, ncoeff=8, top=260, floor=195):
    """Top `ncoeff` nonzero master coefficients, reduced mod q(r)."""
    ans = cd.build_ansatz(d2=cs.polys["d2"], d1=cs.polys["d1"],
                          e=cs.polys["e"], sigma=cs.polys["sigma"])
    eng = cd.ConvolutionDescent(ans, c=ce.DEFAULT_C)
    gens, degrees = [], []
    for dgr in range(top, floor - 1, -1):
        c = qreduce(eng.master_coefficient(dgr), cs.marked)
        if c != 0:
            gens.append(sp.expand(c))
            degrees.append(dgr)
        if len(gens) >= ncoeff:
            break
    return gens, degrees


