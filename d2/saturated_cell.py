def run_target(case, ncoeff, timeout, sat_Gr=True, sigma_generic=False,
               chars=(0,), rows_filter=()):
    """The saturated-cell ladder: widen the d2 stratum union, then sigma, then all.

    The generator set is built ONCE per ladder entry and then solved at every
    requested characteristic -- `char = 0` is the exact-Q kill, `char = p > 0`
    is mod-p RECONNAISSANCE (empty over Fbar_p is a prediction, never a kill).
    """
    rows = []
    base = "genSig" if sigma_generic else ("satGr" if sat_Gr else "noGr")
    if ncoeff != 8:
        base += "_n%d" % ncoeff
    mk = lambda **kw: build_cell_system(case, sat_Gr=sat_Gr,
                                        sigma_generic=sigma_generic, **kw)
    ladder = ([("T_dd2le%d_dsig7", d, 0, 1, 1, "target-row-dsig7") for d in (1, 2, 3, 4)]
              + [("T_dd2le%d_dsig8", d, 0, 2, 2, "target-row-dsig8") for d in (1, 2, 3, 4)]
              + [("T_dd2le%d_dsigBOTH", d, 0, 2, 1, "target-row-both") for d in (1, 2, 3)]
              + [("TARGET_full_cell", 4, 0, 2, 1, "target-full-cell")])
    if rows_filter:
        want = set(rows_filter)
        ladder = [L for L in ladder
                  if "%d:%d:%d" % (L[1], L[4], L[3]) in want]
        if not ladder:
            raise SystemExit("FAIL: --rows matched no ladder entry")
    print("\nTARGET -- saturated stratum unions in cell a7_b3000_T2  [%s]" % base)
    for name, dmax, dmin, gmax, gmin, kind in ladder:
        stem = (name % dmax) if "%d" in name else name
        cs = mk(d2_deg_max=dmax, d2_deg_min=dmin, g_deg_max=gmax, g_deg_min=gmin,
                label="%s_%s" % (stem, base))
        t0 = time.time()
        gens, degs = f31_generators(cs, ncoeff=ncoeff)
        build_s = round(time.time() - t0, 1)
        for ch in chars:
            label = "%s_%s%s" % (stem, base, "" if ch == 0 else "_p%d" % ch)
            res, _ = solve(cs, gens, char=ch, timeout=timeout)
            res.update(kind=kind, label=label, note=cs.note, coeff_degrees=degs,
                       build_seconds=build_s,
                       strata=strata_covered(case, cs, dmax, dmin, gmax, gmin))
            rows.append(_report(label, res))
    return rows


def run_gsys(case, timeout, char=0, d2_deg_max=4, g_deg_max=2):
    """The G-system engine (face_kill_sweep.build_state_system) -- COST PROBE."""
    rows = []
    print("\nG-SYSTEM ENGINE (G1,G2,G3,G5body+Phi, spares at sub2 caps 12/14/16)")
    for label, dmax, dmin, gmax, gmin in (
            ("GS_state_dd20_dsig7", 0, None, 1, None),
            ("GS_union_dd2le1_dsig7", 1, 0, 1, 1),
            ("GS_full_cell", d2_deg_max, 0, g_deg_max, 1)):
        cs = build_cell_system(case, d2_deg_max=dmax, d2_deg_min=dmin,
                               g_deg_max=gmax, g_deg_min=gmin, label=label)
        t0 = time.time()
        gens, system = gsys_generators(cs)
        build_s = round(time.time() - t0, 2)
        res, _ = solve(cs, gens, char=char, timeout=timeout)
        res.update(kind="gsys", label=label, note=cs.note, build_seconds=build_s,
                   n_spare_unknowns=len(system.vars))
        print("    build %.2fs, %d equations, %d spare unknowns"
              % (build_s, len(gens), len(system.vars)), flush=True)
        rows.append(_report(label, res))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--controls", action="store_true")
    ap.add_argument("--target", action="store_true")
    ap.add_argument("--gsys", action="store_true")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--no-sat-Gr", action="store_true",
                    help="drop the inherited v_r(sigma) = 2*sum(b) EXACTNESS assumption")
    ap.add_argument("--sigma-generic", action="store_true",
                    help="drop the pattern-B divisor structure on sigma entirely "
                         "(sigma fully generic of the cell's max degree)")
    ap.add_argument("--ncoeff", type=int, default=8)
    ap.add_argument("--timeout", type=float, default=900.0)
    ap.add_argument("--gsys-char", type=int, default=10007)
    ap.add_argument("--rows", default="",
                    help="comma list of ladder entries as dmax:gmin:gmax, "
                         "e.g. 2:1:2 = deg d2 <= 2 and deg sigma in {7,8}")
    ap.add_argument("--chars", default="0",
                    help="comma list of characteristics: 0 = exact Q (a kill), "
                         "p > 0 = mod-p RECONNAISSANCE only")
    ap.add_argument("--out", default=OUT_PATH,
                    help="artifact path (use a distinct one for parallel runs)")
    args = ap.parse_args()
    out_path = args.out
    if not (args.controls or args.target or args.gsys or args.all):
        args.all = True

    print("=" * 78)
    print("SATURATED FLAG-CASE SCHEME -- pilot on sub2 a7_b3000_T2")
    print("=" * 78)
    case = load_cell()
    prof = cell_profile(case)
    print("cell: a_t=%d b=%s %s sigma_zero=%s d2_zero=%s gz=%s"
          % (case["a_t"], case["b"], case["branch"], case["sigma_zero"],
             case["d2_zero"], case["g_zero_levels"]))
    print("states: %d   degree profile: %s" % (len(case["states"]), prof))

    out = {"schema": "d2-saturated-cell-v1",
           "cell": {k: (list(v) if isinstance(v, (list, tuple)) else v)
                    for k, v in TARGET_CELL.items()},
           "state_count": len(case["states"]),
           "degree_profile": {k: v for k, v in prof.items()},
           "ncoeff": args.ncoeff, "rows": []}

    if args.controls or args.all:
        out["rows"] += run_controls(case, args.ncoeff, args.timeout)
    if args.target or args.all:
        out["rows"] += run_target(case, args.ncoeff, args.timeout,
                                  sat_Gr=not args.no_sat_Gr,
                                  sigma_generic=args.sigma_generic,
                                  chars=tuple(int(c) for c in args.chars.split(",")),
                                  rows_filter=tuple(
                                      x for x in args.rows.split(",") if x))
    if args.gsys or args.all:
        out["rows"] += run_gsys(case, args.timeout, char=args.gsys_char)

    # MERGE, never clobber: a section run alone must not drop the other
    # sections' evidence from the artifact.
    if os.path.exists(out_path):
        try:
            prev = json.load(open(out_path, encoding="utf-8"))
        except Exception:
            prev = {}
        fresh = {r["label"] for r in out["rows"] if "label" in r}
        keep = [r for r in prev.get("rows", []) if r.get("label") not in fresh]
        out["rows"] = keep + out["rows"]

    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, sort_keys=True, default=str)
    print("\nwrote", os.path.basename(out_path))

    bad = [r for r in out["rows"]
           if r.get("expect") and r["verdict"] != r["expect"]]
    if bad:
        print("*** CONTROL MISMATCH on %d run(s) -- the pipeline is NOT validated ***"
              % len(bad))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
