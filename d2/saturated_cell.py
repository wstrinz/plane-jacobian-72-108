def load_cell(spec=TARGET_CELL):
    data = json.load(open(UNIVERSE, encoding="utf-8"))
    hits = [c for c in data["cases"]
            if c["a_t"] == spec["a_t"] and tuple(c["b"]) == tuple(spec["b"])
            and c["branch"] == spec["branch"]
            and bool(c["sigma_zero"]) == spec["sigma_zero"]
            and bool(c["d2_zero"]) == spec["d2_zero"]
            and tuple(c["g_zero_levels"]) == tuple(spec["g_zero_levels"])]
    if len(hits) != 1:
        raise SystemExit("FAIL: cell spec matched %d cases, expected 1" % len(hits))
    case = hits[0]
    if case["state_count"] != len(case["states"]):
        raise SystemExit("FAIL: declared state_count %d != %d listed"
                         % (case["state_count"], len(case["states"])))
    return case


def _d(v):
    return None if v in ("-inf", None) else int(v)


def cell_profile(case):
    """Degree sets of d2/d1/sigma/e over the cell; assert the PRODUCT shape.

    The stratum union is a single saturation only if the state set is the full
    product of per-polynomial degree INTERVALS.  If it is not, this fails loud
    rather than silently over-covering the cell.
    """
    keys = ("deg_d2", "deg_d1", "deg_sigma", "deg_e")
    sets = {k: sorted({_d(st[k]) for st in case["states"]},
                      key=lambda x: (x is None, x)) for k in keys}
    for k, vals in sets.items():
        ints = [v for v in vals if v is not None]
        if ints and ints != list(range(min(ints), max(ints) + 1)):
            raise SystemExit("FAIL: %s degrees %s are not an interval" % (k, vals))
    prod = 1
    for vals in sets.values():
        prod *= len(vals)
    if prod != len(case["states"]):
        raise SystemExit("FAIL: cell is not a product of degree intervals "
                         "(%d combinations vs %d states)" % (prod, len(case["states"])))
    return sets


