def blocked_pairs(ed: ExpData, limit=10):
    """For pairs of occurring variables whose columns are NOT proportional,
    record a witness monomial.  This is the 'why not' diagnosis that makes a
    refusal informative rather than a bare no."""
    present = ed.occurring()
    out = []
    for a, b in itertools.combinations(present, 2):
        ca, cb = ed.column(a), ed.column(b)
        _, ua = _primitive(ca)
        _, ub = _primitive(cb)
        if ua == ub:
            continue
        wit = None
        for i, m in enumerate(ed.mons):
            if (ca[i] == 0) != (cb[i] == 0):
                wit = m
                break
        if wit is None:
            for i, m in enumerate(ed.mons):
                if ua[i] != ub[i]:
                    wit = m
                    break
        if wit is not None:
            out.append({"pair": (str(ed.vars[a]), str(ed.vars[b])),
                        "witness_monomial": ed.mon_str(wit),
                        "witness_poly": ed.which_poly(wit)})
        if len(out) >= limit:
            break
    return out


def lens(polys, variables, labels=None, name="system", max_subset=4,
         verbose=True, do_lattice=True, zname="z"):
    ed = ExpData(polys, variables, labels)
    before = ed.stats()
    result = {"name": name, "before": before, "proposals": [], "refusals": [],
              "single_site": ed.single_site_vars()}

    cands = ray_merge_classes(ed)
    for ci, cand in enumerate(cands):
        ok, ks, viol = check_exclusivity(ed, cand["var_idx"], cand["alpha"])
        zn = zname if len(cands) == 1 else "%s%d" % (zname, ci + 1)
        if not ok:
            result["refusals"].append({"vars": cand["vars"], "violations": viol[:4]})
            continue
        new_polys, new_vars, z, lift_ok = apply_merge(ed, cand["var_idx"],
                                                      cand["alpha"], zn)
        num_ok = numeric_lift_check(ed, new_polys, cand["var_idx"], cand["alpha"], z)
        after = ExpData(new_polys, new_vars, ed.labels).stats()
        result["proposals"].append({
            "rank": 1, "vars": cand["vars"], "alpha": cand["alpha"], "z": zn,
            "z_def": str(merge_expr(ed, cand["var_idx"], cand["alpha"])),
            "before": before, "after": after,
            "gain": {k: before[k] - after[k] for k in before},
            "exclusivity": ok, "lift_ok": lift_ok, "numeric_ok": num_ok,
            "obligation": obligation_text(ed, cand["var_idx"], cand["alpha"], zn,
                                          ok, len(ed.mons), lift_ok, num_ok, 1),
            "new_polys": new_polys, "new_vars": new_vars,
        })

    result["blocked"] = blocked_pairs(ed)
    el = exponent_lattice(ed)
    result["exponent_lattice"] = el
    result["lattice"] = (lattice_merges(ed, max_subset=max_subset, level_a=cands,
                                       ed_lattice=el) if do_lattice else [])
    if verbose:
        print_report(ed, result)
    result["_ed"] = ed
    return result


