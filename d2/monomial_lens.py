def scalar_R9(verbose=True, max_subset=3):
    """The lens at the SCALAR level of the R9 z=1 state -- the level at which a
    latent coordinate would actually help a solve.

    WHY THIS DOES NOT NEED THE (very expensive) y-COEFFICIENT SPLIT.
    bigrade_annotator.build_R3() emits one scalar equation per y-order: the
    y-coefficients of H2,H3,H5 after the state substitution.  Splitting by
    y-degree PARTITIONS terms; it neither creates nor destroys monomials in the
    spare unknowns.  Formally: view the substituted generator as a polynomial in
    the unknowns with coefficients in Q[y, params]; the coefficient of an
    unknown-monomial is a polynomial in y whose j-th coefficient is exactly that
    monomial's coefficient in the j-th scalar equation, so it vanishes iff the
    monomial is absent from EVERY scalar equation.  The union of the supports of
    the scalar equations therefore equals the support of the unsplit expression.
    LEVEL A and LEVEL B read only that union, so they are unaffected -- and the
    unsplit form costs ~100 s instead of the documented multi-hour sympy trap.
    (LEVEL C would differ, since it wants a constant per equation; it is not
    used here.)

    The state ansatz below mirrors bigrade_annotator.build_R3 verbatim; the H
    generators themselves are loaded through ba._H_generators().
    """
    ba = _import_bigrade()
    y = ba.y
    d0, d1, d2, dm1, dm2, dm3, dm4, Phi = ba._gsystem_symbols()
    gamma, r = sp.symbols("gamma r")
    a = sp.symbols("a0 a1 a2 a3 a4")
    g = sp.symbols("g0 g1")
    d2v = sum(a[i] * y**i for i in range(5))
    d1v = sp.Integer(0)
    ev = gamma * (y + 1)**9 * (y - r)
    sigma = sp.expand((y - r)**2 * (g[0] + g[1] * y))
    d0v = sp.expand((d2v**2 + sigma) / 4)
    R = sp.symbols("R0:13")                     # dm2 spare, sub2 cap 12
    S = sp.symbols("S0:15")                     # dm3 spare, sub2 cap 14
    dm2v = sum(R[i] * y**i for i in range(13))
    dm3v = sum(S[i] * y**i for i in range(15))
    subs = {d0: d0v, d1: d1v, d2: d2v, dm1: ev, dm2: dm2v, dm3: dm3v,
            Phi: ba._phi_stripped()}
    Hs = ba._H_generators()
    labels = sorted(Hs)
    polys = [sp.expand(Hs[k][0].xreplace(subs)) for k in labels]

    unknowns = list(R) + list(S)
    params = [gamma, r] + list(a) + list(g)
    out = {}
    res_u = lens(polys, unknowns, labels,
                 name="R9 SCALAR  variables = the %d spare unknowns R0..R12,S0..S14"
                      % len(unknowns),
                 verbose=verbose, max_subset=max_subset, zname="z")
    out["unknowns_only"] = {"n_merges": len(res_u["proposals"]),
                            "n_refusals": len(res_u["refusals"]),
                            "before": res_u["before"],
                            "exponent_lattice": {k: v for k, v in
                                                 res_u["exponent_lattice"].items()
                                                 if k != "null_gradings"}}
    res_a = lens(polys, unknowns + params, labels,
                 name="R9 SCALAR  variables = %d spare unknowns + %d state parameters"
                      % (len(unknowns), len(params)),
                 verbose=verbose, max_subset=max_subset, zname="z")
    out["unknowns_and_params"] = {"n_merges": len(res_a["proposals"]),
                                  "n_refusals": len(res_a["refusals"]),
                                  "before": res_a["before"],
                                  "exponent_lattice": {k: v for k, v in
                                                       res_a["exponent_lattice"].items()
                                                       if k != "null_gradings"}}
    if verbose:
        print(">>> R9 SCALAR SUMMARY")
        for k, v in out.items():
            print("      %-22s LEVEL A merges %d, refusals %d, torus dim %d"
                  % (k, v["n_merges"], v["n_refusals"],
                     v["exponent_lattice"]["torus_dim"]))
        print()
    return out


