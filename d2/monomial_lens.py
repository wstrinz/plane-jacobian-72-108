class ExpData:
    """Exponent matrix of a system over a declared variable list.

    Symbols NOT in `variables` are treated as coefficients (they live in the
    coefficient domain of the sympy Poly) and are invisible to the lens.
    """

    def __init__(self, polys, variables, labels=None):
        self.vars = [sp.sympify(v) for v in variables]
        self.n = len(self.vars)
        self.polys = [sp.expand(sp.sympify(p)) for p in polys]
        self.labels = list(labels) if labels else ["f%d" % i for i in range(len(self.polys))]
        self.mons = []            # deduplicated global list of exponent tuples
        self.per_poly = []
        self.coeffs = []
        seen = {}
        pos = {v: i for i, v in enumerate(self.vars)}
        for f in self.polys:
            if f == 0:
                self.per_poly.append([])
                self.coeffs.append([])
                continue
            ms, cs = self._split(f, pos)
            self.per_poly.append(ms)
            self.coeffs.append(cs)
            for m in ms:
                if m not in seen:
                    seen[m] = len(self.mons)
                    self.mons.append(m)
        self.index = seen
        self._cols = None

    @staticmethod
    def _split(f, pos):
        """Split an EXPANDED polynomial into (exponent tuples, coefficient parts)
        over the declared variables, walking the expression tree directly.

        sp.Poly(f, *vars) is equivalent but builds a multivariate domain over all
        declared generators, which is prohibitive at 30+ variables and 10^5 terms;
        this walk is linear in the number of terms.  Fail-loud on any non
        nonnegative-integer exponent of a declared variable.
        """
        n = len(pos)
        ms, cs = [], []
        for term in sp.Add.make_args(f):
            exps = [0] * n
            coeff = sp.Integer(1)
            for fac in sp.Mul.make_args(term):
                base, e = fac.as_base_exp()
                j = pos.get(base)
                if j is None:
                    coeff *= fac
                    continue
                if not (e.is_Integer and e >= 0):
                    raise ValueError(
                        "declared variable %s occurs with exponent %s (not a "
                        "nonnegative integer); the lens needs a polynomial input"
                        % (base, e))
                exps[j] += int(e)
            ms.append(tuple(exps))
            cs.append(coeff)
        return ms, cs

    def column(self, j):
        if self._cols is None:
            self._cols = [tuple(m[j] for m in self.mons) for j in range(self.n)]
        return self._cols[j]

    def occurring(self):
        return [j for j in range(self.n) if any(self.column(j))]

    def mon_str(self, m):
        parts = []
        for j, e in enumerate(m):
            if e == 1:
                parts.append(str(self.vars[j]))
            elif e:
                parts.append("%s^%d" % (self.vars[j], e))
        return "*".join(parts) if parts else "1"

    def which_poly(self, mon):
        for lab, ms in zip(self.labels, self.per_poly):
            if mon in ms:
                return lab
        return "?"

    def single_site_vars(self):
        """Variables occurring in exactly one distinct monomial of the system."""
        out = []
        for j in range(self.n):
            col = self.column(j)
            nz = [i for i, e in enumerate(col) if e]
            if len(nz) == 1:
                out.append((str(self.vars[j]), self.mon_str(self.mons[nz[0]])))
        return out

    def stats(self):
        present = self.occurring()
        edges = set()
        for m in self.mons:
            sup = [j for j in range(self.n) if m[j]]
            for a, b in itertools.combinations(sorted(sup), 2):
                edges.add((a, b))
        parent = {j: j for j in present}

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        for a, b in edges:
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[ra] = rb
        comps = len({find(j) for j in present}) if present else 0
        deg = {j: 0 for j in present}
        for a, b in edges:
            deg[a] += 1
            deg[b] += 1
        return {
            "n_declared_vars": self.n,
            "n_occurring_vars": len(present),
            "n_distinct_monomials": len(self.mons),
            "max_total_degree": max((sum(m) for m in self.mons), default=0),
            "graph_edges": len(edges),
            "graph_components": comps,
            "graph_max_degree": max(deg.values()) if deg else 0,
        }


# =====================================================================
#  1.  LEVEL A -- rank-1 (ray) merges, via column proportionality
# =====================================================================
def _primitive(vec):
    """(g, u) with vec = g*u and u a primitive integer vector; (0, None) if 0."""
    g = 0
    for e in vec:
        g = gcd(g, abs(int(e)))
    if g == 0:
        return 0, None
    return g, tuple(int(e) // g for e in vec)


def ray_merge_classes(ed: ExpData):
    """ALL maximal rank-1 merges (complete, see module docstring)."""
    buckets = {}
    for j in range(ed.n):
        g, u = _primitive(ed.column(j))
        if u is None:
            continue                        # variable does not occur at all
        buckets.setdefault(u, []).append((j, g))
    out = []
    for u, members in buckets.items():
        if len(members) < 2:
            continue
        gs = [g for _, g in members]
        G = 0
        for g in gs:
            G = gcd(G, g)
        alpha = [g // G for g in gs]
        idx = [j for j, _ in members]
        out.append({
            "vars": [str(ed.vars[j]) for j in idx],
            "var_idx": idx,
            "alpha": alpha,
            "rank": 1,
        })
    out.sort(key=lambda d: -len(d["vars"]))
    return out


def merge_expr(ed: ExpData, var_idx, alpha):
    e = sp.Integer(1)
    for j, a in zip(var_idx, alpha):
        e *= ed.vars[j] ** a
    return e


# =====================================================================
#  2.  soundness: (H1), (H2), the lift, the checks, the obligation text
# =====================================================================
def check_exclusivity(ed: ExpData, var_idx, alpha):
    """(H1).  Returns (ok, k_per_global_monomial, violations)."""
    viol = []
    ks = []
    for m in ed.mons:
        restricted = [m[j] for j in var_idx]
        if all(e == 0 for e in restricted):
            ks.append(0)
            continue
        k, bad = None, False
        for e, a in zip(restricted, alpha):
            if a == 0:
                if e != 0:
                    bad = True
                    break
                continue
            if e % a != 0:
                bad = True
                break
            kk = e // a
            if k is None:
                k = kk
            elif k != kk:
                bad = True
                break
        if bad or k is None or k < 0:
            viol.append({
                "poly": ed.which_poly(m),
                "monomial": ed.mon_str(m),
                "restriction": {str(ed.vars[j]): m[j] for j in var_idx},
                "reason": "S-restriction is not a nonnegative integer multiple of alpha",
            })
            ks.append(None)
        else:
            ks.append(k)
    return (not viol), ks, viol


def apply_merge(ed: ExpData, var_idx, alpha, zname="z"):
    """Rewrite in quotient coordinates.  Returns (new_polys, new_vars, z, lift_ok).
    Raises if (H1) fails -- the tool never silently applies an unsound merge."""
    ok, ks, viol = check_exclusivity(ed, var_idx, alpha)
    if not ok:
        raise ValueError("UNSOUND merge refused: %r" % (viol[:2],))
    S = set(var_idx)
    z = sp.Symbol(zname)
    keep = [j for j in range(ed.n) if j not in S]
    new_vars = [ed.vars[j] for j in keep] + [z]
    new_polys = []
    for ms, cs in zip(ed.per_poly, ed.coeffs):
        acc = sp.Integer(0)
        for m, c in zip(ms, cs):
            k = ks[ed.index[m]]
            term = sp.sympify(c)
            for j in keep:
                if m[j]:
                    term *= ed.vars[j] ** m[j]
            if k:
                term *= z ** k
            acc += term
        new_polys.append(sp.expand(acc))
    phi = {z: merge_expr(ed, var_idx, alpha)}
    lift_ok = all(sp.expand(g.xreplace(phi) - f) == 0
                  for g, f in zip(new_polys, ed.polys))
    return new_polys, new_vars, z, lift_ok


def numeric_lift_check(ed: ExpData, new_polys, var_idx, alpha, z, trials=5, seed=11):
    """Exact-rational spot check: sample x, set z = x^alpha, compare g and f."""
    rng = random.Random(seed)
    S = set(var_idx)
    params = set()
    for f in ed.polys:
        params |= f.free_symbols
    params -= set(ed.vars)
    for _ in range(trials):
        pt = {v: sp.Rational(rng.randint(1, 9), rng.randint(1, 5)) for v in ed.vars}
        pt.update({s: sp.Rational(rng.randint(1, 9), rng.randint(1, 5)) for s in params})
        zval = sp.Integer(1)
        for j, a in zip(var_idx, alpha):
            zval *= pt[ed.vars[j]] ** a
        down = {ed.vars[j]: pt[ed.vars[j]] for j in range(ed.n) if j not in S}
        down.update({s: pt[s] for s in params})
        down[z] = zval
        for g, f in zip(new_polys, ed.polys):
            if sp.nsimplify(g.xreplace(down) - f.xreplace(pt)) != 0:
                return False
    return True


def obligation_text(ed, var_idx, alpha, zname, exclusivity_ok, n_mon_checked,
                    lift_ok, numeric_ok, rank=1):
    S = [str(ed.vars[j]) for j in var_idx]
    zdef = "*".join("%s^%d" % (s, a) if a != 1 else s for s, a in zip(S, alpha))
    L = ["SOUNDNESS OBLIGATION for  %s := %s" % (zname, zdef),
         "  (H1) EXCLUSIVITY -- every monomial of every input polynomial restricts",
         "       on {%s} to a nonnegative integer multiple of alpha = %s."
         % (", ".join(S), tuple(alpha)),
         "       CHECKED on %d distinct monomials: %s"
         % (n_mon_checked, "PASS" if exclusivity_ok else "*** FAIL -- REFUSED ***"),
         "  (H2) NONDEGENERACY -- alpha_v >= 1 for every merged v:  %s"
         % ("PASS" if all(a >= 1 for a in alpha) else "*** FAIL ***"),
         "  (L1) LIFT EXACTNESS -- phi(g_i) - f_i == 0 identically, all i:  %s"
         % ("PASS" if lift_ok else "*** FAIL ***"),
         "  (L2) NUMERIC CROSS-CHECK -- random exact-rational points:  %s"
         % ("PASS" if numeric_ok else "*** FAIL ***")]
    if rank == 1:
        L += ["  ==> LEMMA L applies: for every subset U of the surviving variables,",
              "      J cap Q[U] = I cap Q[U].  LOSSLESS in both directions."]
    else:
        L += ["  ==> rank-%d merge: only J cap Q[U] <= I cap Q[U] is claimed." % rank,
              "      UNDISCHARGED: the converse needs B free over phi(A), which can",
              "      FAIL for a rank->=2 monoid.  Verify separately."]
    return "\n".join(L)


# =====================================================================
#  3.  LEVEL B -- higher-rank lattice degeneracy on variable subsets
# =====================================================================
def _rank_frac(rows):
    M = [[Fraction(int(x)) for x in r] for r in rows]
    nr, nc = len(M), (len(M[0]) if M else 0)
    rank = 0
    for c in range(nc):
        piv = None
        for i in range(rank, nr):
            if M[i][c] != 0:
                piv = i
                break
        if piv is None:
            continue
        M[rank], M[piv] = M[piv], M[rank]
        pv = M[rank][c]
        M[rank] = [x / pv for x in M[rank]]
        for i in range(nr):
            if i != rank and M[i][c] != 0:
                f = M[i][c]
                M[i] = [a - f * b for a, b in zip(M[i], M[rank])]
        rank += 1
        if rank == nr:
            break
    return rank


def _nonneg_int_combo(target, gens):
    """Exact solve target = sum k_i gens_i; return the integer nonneg k or None."""
    ncol = len(gens)
    A = sp.Matrix([[sp.Integer(g[j]) for g in gens] for j in range(len(target))])
    b = sp.Matrix([sp.Integer(t) for t in target])
    aug = A.row_join(b)
    if A.rank() != aug.rank():
        return None
    x = A.solve_least_squares(b)
    if sp.simplify(A * x - b) != sp.zeros(A.rows, 1):
        return None
    out = []
    for v in x:
        v = sp.Rational(sp.nsimplify(v))
        if v < 0 or v.q != 1:
            return None
        out.append(int(v))
    return out if len(out) == ncol else None


def _independent_rows(rows, ncols):
    """Exact greedy elimination: return original rows forming a basis of the row
    space (at most ncols of them).  Stops as soon as full rank is reached."""
    red, piv, orig = [], [], []
    for row in rows:
        v = [Fraction(int(x)) for x in row]
        for b, pc in zip(red, piv):
            if v[pc] != 0:
                f = v[pc]
                v = [a - f * c for a, c in zip(v, b)]
        nz = next((i for i, x in enumerate(v) if x != 0), None)
        if nz is None:
            continue
        inv = v[nz]
        v = [x / inv for x in v]
        red.append(v)
        piv.append(nz)
        orig.append(row)
        if len(red) == ncols:
            break
    return orig


def exponent_lattice(ed: ExpData):
    """Rank of the Z-span of the exponent rows, restricted to occurring variables.

    torus_dim = (#occurring vars) - rank is the dimension of the space of weight
    vectors under which EVERY monomial has weight 0.  torus_dim = 0 is the
    strongest possible negative result: the system admits no monomial change of
    coordinates that loses a variable, not even a Laurent one."""
    present = ed.occurring()
    rows = sorted({tuple(m[j] for j in present) for m in ed.mons})
    rows = [r for r in rows if any(r)]
    ind = _independent_rows(rows, len(present))
    r = len(ind)
    gens = []
    if rows and len(present) - r > 0:
        M = sp.Matrix([[sp.Integer(x) for x in row] for row in ind])
        for v in M.nullspace():
            rats = [sp.Rational(sp.nsimplify(x)) for x in v]
            den = sp.ilcm(*[q.q for q in rats])
            ints = [int(q * den) for q in rats]
            g = 0
            for x in ints:
                g = gcd(g, abs(x))
            if g:
                ints = [x // g for x in ints]
            gens.append({str(ed.vars[j]): e for j, e in zip(present, ints) if e})
    return {"n_occurring": len(present), "lattice_rank": r,
            "torus_dim": len(present) - r, "null_gradings": gens}


def _low_support_relations(null_basis, bound=3, max_report=12):
    """Minimal-support nonzero integer vectors in the lattice spanned by
    `null_basis` (a list of integer tuples).  Small integer combinations are
    enumerated; for dimension 1 this is exact, for higher dimension it is a
    bounded search and is reported as such."""
    d = len(null_basis)
    if d == 0:
        return []
    n = len(null_basis[0])
    seen = {}
    rng = range(-bound, bound + 1)
    for coeffs in itertools.product(rng, repeat=d):
        if all(c == 0 for c in coeffs):
            continue
        v = [sum(c * b[j] for c, b in zip(coeffs, null_basis)) for j in range(n)]
        if not any(v):
            continue
        g = 0
        for x in v:
            g = gcd(g, abs(x))
        v = tuple(x // g for x in v)
        if v[next(i for i, x in enumerate(v) if x)] < 0:
            v = tuple(-x for x in v)
        sup = frozenset(i for i, x in enumerate(v) if x)
        if sup not in seen:
            seen[sup] = v
    best = sorted(seen.items(), key=lambda kv: len(kv[0]))
    return [(sorted(s), v) for s, v in best[:max_report]]


def lattice_merges(ed: ExpData, max_subset=6, max_rows_for_gens=20, level_a=None,
                   ed_lattice=None):
    """LEVEL B -- degenerate variable subsets, found via LOW-SUPPORT LATTICE
    RELATIONS instead of a blind subset scan.

    KEY FACT (this is what makes the search both complete and cheap): if a
    subset S has rank(M_S) < |S| then some nonzero weight vector w supported
    inside S satisfies M_S w_S = 0; extending w by zero gives M w = 0.  So EVERY
    degenerate subset contains the support of a nonzero vector of the global
    exponent-matrix null space.  In particular:

        torus_dim = 0  ==>  NO subset of ANY size is degenerate.

    The scan therefore reduces to: compute the null space, extract its minimal
    supports, and test those (and nothing else).  Results whose whole rank drop
    is already explained by a LEVEL A class are flagged `subsumed`.
    """
    present = ed.occurring()
    el = ed_lattice if ed_lattice is not None else exponent_lattice(ed)
    if el["torus_dim"] == 0:
        return []                       # PROVED empty -- no scan needed
    rows = sorted({tuple(m[j] for j in present) for m in ed.mons})
    rows = [r for r in rows if any(r)]
    ind = _independent_rows(rows, len(present))
    M = sp.Matrix([[sp.Integer(x) for x in r] for r in ind])
    basis = []
    for v in M.nullspace():
        rats = [sp.Rational(sp.nsimplify(x)) for x in v]
        den = sp.ilcm(*[q.q for q in rats])
        basis.append(tuple(int(q * den) for q in rats))
    a_classes = [set(c["var_idx"]) for c in (level_a or [])]
    found = []
    for sup_local, vec in _low_support_relations(basis):
        S = [present[i] for i in sup_local]
        if len(S) < 2 or len(S) > max_subset:
            continue
        srows = sorted({tuple(m[j] for j in S) for m in ed.mons})
        srows = [r for r in srows if any(r)]
        if len(srows) < 2:
            continue
        r = _rank_frac(srows)
        if r >= len(S):
            continue
        gens_ok = None
        for gens in itertools.combinations(srows[:max_rows_for_gens], r):
            if _rank_frac(list(gens)) < r:
                continue
            if all(_nonneg_int_combo(row, list(gens)) is not None for row in srows):
                gens_ok = gens
                break
        names = [str(ed.vars[j]) for j in S]
        explained = sum(max(0, len(c & set(S)) - 1) for c in a_classes)
        found.append({
            "vars": names,
            "var_idx": list(S),
            "rank": r,
            "relation": {names[i]: vec[j] for i, j in enumerate(sup_local)},
            "subsumed": (len(S) - r) <= explained,
            "realisable": gens_ok is not None,
            "generators": ["*".join("%s^%d" % (names[i], e) if e != 1 else names[i]
                                    for i, e in enumerate(g) if e)
                           for g in gens_ok] if gens_ok else None,
        })
    return found


