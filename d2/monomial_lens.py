#!/usr/bin/env python3
"""monomial_lens.py -- automatic detection of latent quotient coordinates.

THE QUESTION.  Given a polynomial system f_1..f_m in declared variables V, do
some of the variables occur ONLY through a fixed monomial combination?  If they
do, naming that combination as a single new variable shrinks the system, and the
shrunk system's elimination ideals contract back EXACTLY (Lemma L below).  This
is the mechanism that collapsed GGHV22's "using a CAS (for example Mathematica)"
step at tex line 1689 (see GGHV_LINE1689.md): C_3 and F_-4 occur in the nine
printed equations only through E := F_-4 * C_3^23, after which the elimination is
a 3-equation / 2-unknown hand computation.

WHAT THIS MODULE DOES
  * builds the exponent matrix of the system over the declared variables;
  * LEVEL A (rank 1, COMPLETE): finds every maximal set S of variables whose
    exponent COLUMNS are pairwise proportional -- equivalently whose restricted
    exponent rows all lie on a single ray of the exponent lattice -- and emits
    z = prod_{v in S} v^{alpha_v}.  Because column proportionality is an
    equivalence relation, grouping columns by their primitive direction
    enumerates every maximal rank-1 merge and misses none;
  * LEVEL B (rank r >= 2): scans variable subsets for lattice degeneracy
    rank(M_S) = r < |S| and tries to realise it by r new coordinates;
  * LEVEL C: solves for the weight vectors making each input polynomial
    weighted-homogeneous (this is how the (72,108) u-weight grading is
    recovered mechanically rather than assumed);
  * for every proposal prints before/after statistics and an explicit
    SOUNDNESS OBLIGATION, and RUNS the machine-checkable parts of it;
  * REFUSES, with a named witness monomial, whenever a candidate variable also
    occurs outside the proposed combination.

SOUNDNESS.

  Let V be the declared variables, S a subset of V, alpha in Z_{>0}^S primitive.
  Write x^alpha = prod_{v in S} v^{alpha_v}, W = V \\ S, and let
      phi : A := Q[W][z]  -->  B := Q[V],   z |-> x^alpha,  phi|_{Q[W]} = id.

  (H1) EXCLUSIVITY.  For every monomial m of every f_i, the restriction of m's
       exponent vector to S equals k_m * alpha with k_m an integer >= 0.
  (H2) NONDEGENERACY.  alpha_v >= 1 for every v in S.

  Under (H1) each f_i has a unique preimage g_i in A, and:

  LEMMA L (contraction).  Assume (H1),(H2).  Put I = (f_1..f_m) in B and
  J = (g_1..g_m) in A.  Then for every subset U of W,   J cap Q[U] = I cap Q[U].

  Proof.  phi is injective on monomials (alpha != 0, and S and W are disjoint),
  so g_i is well defined and phi(J) is contained in I -- the "<=" direction,
  which is all a necessary-condition elimination needs.  For ">=": by (H2) every
  m in N^S factors uniquely as m = k*alpha + m' with k = min_v floor(m_v/alpha_v)
  and m' not >= alpha, so B is a FREE phi(A)-module on the basis
  {x^{m'} : m' in N^S, m' not >= alpha}, which contains 1.  Let pi : B -> phi(A)
  be the phi(A)-linear projection onto the basis element 1.  If h in I cap Q[U]
  then h = sum c_i f_i, and since h lies in phi(A)*1, h = pi(h) = sum pi(c_i) f_i
  lies in the phi(A)-ideal generated by the f_i, i.e. in phi(J).  phi is
  injective and h is in Q[U] which sits inside A, so h is in J cap Q[U].  QED

  So a LEVEL A merge is LOSSLESS for elimination into any subset of the surviving
  variables: nothing is added and nothing is lost.  For LEVEL B (r >= 2 new
  coordinates) only "<=" is claimed here -- freeness of B over phi(A) can fail
  for a rank-r monoid -- so the converse is printed as an UNDISCHARGED
  obligation rather than asserted.

  If (H1) fails the substitution is UNSOUND; the tool refuses and names the
  offending polynomial and monomial.

REGRESSION SUITE (`--quiet` exits 0 iff all behave as recorded):
  1  GGHV22 tex-1689, the nine printed equations -> must rediscover E = F_-4*C_3^23
  1b control: the same with the three equations the paper drops -> must REFUSE
  2  the seven G5body terms -> must recover d0=4,d1=3,d2=2,dm1=5,dm2=6,dm3=7,
     dm4=8 with common u-weight 17, from the monomials alone
  3  a deliberate negative control -> must REFUSE (plus a positive control)
  4  the R9 z=1 dm4-eliminated H-system -> reports whatever it finds

Read-only on every existing artifact.  Exact arithmetic throughout; the only
randomness is an extra exact-rational spot check of the lift.
"""
