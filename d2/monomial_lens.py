def regression_3(verbose=True):
    """f1 = a*b^2 + c ;  f2 = a^2*b^4*c - 3 = (a b^2)^2 c - 3 ;  f3 = b + c.
    `b` occurs both inside the product a*b^2 and ON ITS OWN in f3, so merging
    {a,b} is UNSOUND and the tool must refuse.  Positive control: drop f3 and
    the merge must reappear."""
    a, b, c = sp.symbols("a b c")
    bad = [a*b**2 + c, a**2*b**4*c - 3, b + c]
    good = [a*b**2 + c, a**2*b**4*c - 3]
    res_bad = lens(bad, [a, b, c], ["f1", "f2", "f3"],
                   name="REG3  NEGATIVE control (b occurs inside AND outside a*b^2)",
                   verbose=verbose, zname="z")
    res_good = lens(good, [a, b, c], ["f1", "f2"],
                    name="REG3  POSITIVE control (the same system without f3 = b + c)",
                    verbose=verbose, zname="z")
    refused = not any(set(p["vars"]) & {"a", "b"} for p in res_bad["proposals"])
    accepted = any(set(p["vars"]) == {"a", "b"} for p in res_good["proposals"])
    # LEMMA L, executed rather than merely proved: eliminate {a,b} upstairs and
    # {z} downstairs and compare the contractions into Q[c].
    z = sp.Symbol("z")
    down = [p for p in res_good["proposals"] if set(p["vars"]) == {"a", "b"}]
    lemma_l = None
    if down:
        gpolys = down[0]["new_polys"]
        zsym = sp.Symbol(down[0]["z"])
        up_elim = [g for g in sp.groebner(good, a, b, c, order="lex").exprs
                   if not (g.has(a) or g.has(b))]
        dn_elim = [g for g in sp.groebner(gpolys, zsym, c, order="lex").exprs
                   if not g.has(zsym)]
        lemma_l = {
            "I_cap_Qc": [str(sp.factor_list(g)[1] and sp.expand(g)) for g in up_elim],
            "J_cap_Qc": [str(sp.expand(g)) for g in dn_elim],
            "equal": (len(up_elim) == len(dn_elim)
                      and all(sp.expand(u * sp.LC(d, c) - d * sp.LC(u, c)) == 0
                              for u, d in zip(up_elim, dn_elim))),
        }
    ed_bad = ExpData(bad, [a, b, c], ["f1", "f2", "f3"])
    exc, ks, viol = check_exclusivity(ed_bad, [0, 1], [1, 2])
    forced_refusal = (not exc) and len(viol) > 0
    # and the forced application must RAISE, not silently proceed
    raised = False
    try:
        apply_merge(ed_bad, [0, 1], [1, 2], "z")
    except ValueError:
        raised = True
    ok = (refused and accepted and forced_refusal and raised
          and bool(lemma_l and lemma_l["equal"]))
    if verbose:
        print(">>> REG3 VERDICT:", "PASS" if ok else "*** FAIL ***")
        print("      refused on the bad system         : %s" % refused)
        print("      accepted on the good system       : %s" % accepted)
        print("      forced z=a*b^2 rejected by (H1)   : %s" % forced_refusal)
        print("      apply_merge() raised on the force : %s" % raised)
        if lemma_l:
            print("      LEMMA L executed on the positive control:")
            print("         I cap Q[c] (eliminate a,b upstairs) = %s" % lemma_l["I_cap_Qc"])
            print("         J cap Q[c] (eliminate z downstairs) = %s" % lemma_l["J_cap_Qc"])
            print("         equal up to scalars: %s" % lemma_l["equal"])
        if viol:
            print("      refusal witness: %s, monomial %s"
                  % (viol[0]["poly"], viol[0]["monomial"]))
        print()
    return ok, {"refused": refused, "accepted": accepted,
                "forced_refusal": forced_refusal, "raised": raised,
                "lemma_l": lemma_l,
                "witness": viol[0] if viol else None}


