def _gghv_series(N=14):
    """Regenerate (D~^2)_{-k}, (D~^3)_{-k}, (D~^{-1})_{-k} from the series
    definition of D~ = x^3 + x d_1 + d_0 + x^{-1}d_{-1} + ... (d_3=1, d_2=0),
    the same construction as the scratchpad gen_eqs.py.  Used both to build the
    equations the paper OMITS and to re-verify the nine printed ones."""
    t = sp.Symbol("t")
    d = {3: sp.Integer(1), 2: sp.Integer(0), 1: sp.Symbol("d1"), 0: sp.Symbol("d0")}
    for k in range(1, N + 1):
        d[-k] = sp.Symbol("dm%d" % k)
    TRUNC = N + 6
    A = sum(d[k] * t ** (3 - k) for k in sorted(d, reverse=True))

    def trunc(expr):
        p = sp.expand(expr)
        return sum(p.coeff(t, i) * t ** i for i in range(TRUNC + 1))

    A2 = trunc(sp.expand(A ** 2))
    A3 = trunc(sp.expand(A ** 3))
    Ainv = sp.Integer(1)
    rest = trunc(A - 1)
    term = sp.Integer(1)
    for _ in range(1, TRUNC + 1):
        term = trunc(term * (-rest))
        Ainv = Ainv + term
    Ainv = trunc(Ainv)
    D2 = lambda k: sp.expand(sp.expand(A2).coeff(t, k + 6))          # noqa: E731
    D3 = lambda k: sp.expand(sp.expand(A3).coeff(t, k + 9))          # noqa: E731
    Dinv = lambda k: (sp.Integer(0) if k - 3 < 0                     # noqa: E731
                      else sp.expand(sp.expand(Ainv).coeff(t, k - 3)))
    return D2, D3, Dinv, d


