#  4.  LEVEL C -- weighted-homogeneity gradings
# =====================================================================
def grading_space(ed: ExpData):
    """Solve for w in Q^n and per-polynomial constants c_f with
    <exponent(m), w> = c_f for every monomial m of f.  Coordinates of the
    returned nullspace vectors are (w_1..w_n, c_1..c_m)."""
    nvar, npol = ed.n, len(ed.polys)
    rows = []
    for pi, ms in enumerate(ed.per_poly):
        for m in ms:
            row = [sp.Integer(e) for e in m] + [sp.Integer(0)] * npol
            row[nvar + pi] = sp.Integer(-1)
            rows.append(row)
    if not rows:
        return {"dim": nvar + npol, "basis": [], "n_constraints": 0}
    M = sp.Matrix(rows)
    ns = M.nullspace()
    return {"dim": len(ns), "basis": [list(v) for v in ns], "n_constraints": M.rows,
            "vars": [str(v) for v in ed.vars], "polys": list(ed.labels)}


def grading_contains(gs, weights, consts):
    """Exact test: is (w, c) in the span of the grading-space basis?"""
    if not gs["basis"]:
        return all(sp.Rational(x) == 0 for x in list(weights) + list(consts))
    B = sp.Matrix.hstack(*[sp.Matrix(v) for v in gs["basis"]])
    tgt = sp.Matrix([sp.Rational(x) for x in list(weights) + list(consts)])
    return B.rank() == B.row_join(tgt).rank()


def primitive_generator(gs, names):
    """If the grading space is 1-dimensional, return its primitive integer
    generator as a dict {name: weight}; else None."""
    if gs["dim"] != 1:
        return None
    rats = [sp.Rational(sp.nsimplify(x)) for x in gs["basis"][0]]
    den = sp.ilcm(*[r.q for r in rats]) if rats else 1
    ints = [int(r * den) for r in rats]
    g = 0
    for x in ints:
        g = gcd(g, abs(x))
    if g:
        ints = [x // g for x in ints]
    if ints and ints[0] < 0:
        ints = [-x for x in ints]
    return dict(zip(names, ints))


